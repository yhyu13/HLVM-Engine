def create_common_shadermake() -> ShaderMakeModule:
    """Factory function to create ShaderMake module for common shaders (BlitVS, BlitPS).

    These shaders are shared across multiple passes and located in Engine/Source/Runtime/Shader/.
    FCommonRenderPasses uses these by default; tests can override with SetShaderDataDir().
    """
    shader_target_name = "Common_ShaderMake"

    # CMAKE_SOURCE_DIR for Runtime = Engine/Source/Runtime
    shader_dir = "${CMAKE_SOURCE_DIR}/Shader"

    # Config file is in Shader directory
    config_file = "${CMAKE_SOURCE_DIR}/Shader/ShaderMake.cfg"

    # Shader source files for common shaders
    shader_sources = [
        shader_dir + "/BlitVS.hlsl",
        shader_dir + "/BlitPS.hlsl",
    ]

    # Include directories
    include_dirs = [
        shader_dir,
    ]

    return ShaderMakeModule(
        target_name=shader_target_name,
        config_file_cmake=config_file,
        shader_sources_cmake=shader_sources,
        output_dir_cmake=shader_dir,
        include_dirs_cmake=include_dirs,
        project_name="HLVM_Common",
        slang_options=""
    )